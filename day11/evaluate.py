"""Правило проверки пишет участник. Проверяем только утверждение о числе.

Реализация Задания 2 (правило для стороны «правильность расчёта» — calculation).

Контракт (materials/api_practice.md):
- case['expected'] — конечное число, полученное независимо от модели через SQL;
- case['claim']   — конечное число, вручную извлечённое из полного ответа модели,
                    либо None, если утверждения нет или его нельзя однозначно извлечь;
- bool, строка, NaN и бесконечность не считаются числовым утверждением -> «спорно»;
- совпадение однозначного claim с expected -> «прошёл»;
- несовпадение -> «не прошёл»; отсутствие однозначного числа -> «спорно».

Точность сравнения объявлена заранее: абсолютная погрешность не более 0.05
(значения станции округляются до десятых; см. правило №2 в журнале). Правило
сравнивает ТОЛЬКО конечные числа в одних и тех же единицах; перевод единиц,
извлечение claim и смысл expected проверяет человек. Правило не оценивает все
пять сторон качества.
"""

import math

# Заранее объявленная точность сравнения (абсолютная погрешность).
TOLERANCE = 0.05


def _is_number(value):
    """Числовое утверждение: int или float, но не bool, не NaN, не inf."""
    if isinstance(value, bool):
        return False
    if not isinstance(value, (int, float)):
        return False
    return math.isfinite(value)


def evaluate(case):
    # expected тоже должен быть конечным числом: иначе сравнивать не с чем,
    # и это проблема подготовки доказательства, а не ответ модели.
    expected = case.get('expected')
    if not _is_number(expected):
        return {
            'mark': 'спорно',
            'reason': 'expected отсутствует или не является конечным числом: '
                      'независимое основание сравнения не подготовлено; '
                      'оценка модели невозможна (проблема проверки, не ответа).',
        }

    claim = case.get('claim')
    if claim is None:
        return {
            'mark': 'спорно',
            'reason': 'числовое утверждение в ответе отсутствует или не было '
                      'однозначно извлечено человеком; ошибка извлечения — '
                      'проблема проверки, а не доказательство ошибки модели.',
        }
    if not _is_number(claim):
        return {
            'mark': 'спорно',
            'reason': 'claim не является однозначным числом (тип %s: строка, '
                      'bool, NaN или бесконечность не считаются числовым '
                      'утверждением по контракту).' % type(claim).__name__,
        }

    difference = abs(claim - expected)
    if difference <= TOLERANCE:
        return {
            'mark': 'прошёл',
            'reason': 'числовое утверждение %r совпадает с независимым '
                      'результатом SQL %r (разница %g <= допустимой погрешности '
                      '%g); сравнение выполнено в одних единицах.'
                      % (claim, expected, difference, TOLERANCE),
        }
    return {
        'mark': 'не прошёл',
        'reason': 'числовое утверждение %r отличается от независимого '
                  'результата SQL %r на %g, что превышает заранее объявленную '
                  'погрешность %g.' % (claim, expected, difference, TOLERANCE),
    }
