def main() -> None:
    db = sqlite3.connect("src/results.db")
    db.execute("PRAGMA foreign_keys = ON;")
    for idx, (dim, kind, title, expected, sql, reason) in enumerate(CASES):
        cur = db.execute(
            "INSERT INTO cases (dimension_id, kind, title, expected, proof_sql, proof_reason)"
            " VALUES (?, ?, ?, ?, ?, ?)",
            (dim, kind, title, expected, sql, reason),
        )
        case_id = cur.lastrowid
        print(f"case_id={case_id} [{dim}/{kind}] {title}")
        for label, text in PROMPTS[idx]:
            pcur = db.execute(
                "INSERT INTO prompts (case_id, label, text) VALUES (?, ?, ?)",
                (case_id, label, text),
            )
            print(f"   prompt_id={pcur.lastrowid} ({label}): {text}")
    db.commit()
    n_cases = db.execute("SELECT COUNT(*) FROM cases").fetchone()[0]
    n_prompts = db.execute("SELECT COUNT(*) FROM prompts").fetchone()[0]
    print(f"ИТОГО: случаев={n_cases}, формулировок={n_prompts}")
    db.close()


if __name__ == "__main__":
    main()
