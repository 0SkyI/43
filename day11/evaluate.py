"""Правило проверки пишет участник. Проверяем только утверждение о числе.

Реализация числового правила (Задание 2, контракт из materials/api_practice.md):

- expected — конечное число, полученное независимо от модели через SQL;
- claim — конечное число, вручную извлечённое человеком из полного ответа
  модели, либо None, если утверждения нет или его нельзя извлечь однозначно;
- bool, строка, NaN и бесконечность не считаются числовым утверждением —
  такой claim даёт «спорно»;
- совпадение однозначного claim с expected — «прошёл»,
  несовпадение — «не прошёл», отсутствие однозначного числа — «спорно».

Точность сравнения зафиксирована заранее: абсолютная погрешность не более
1e-9 (в базе — счётчики и значения с одним знаком после запятой). Правило
проверяет только одно числовое утверждение: оно НЕ оценивает понимание
данных, смысл рассуждения и остальные четыре стороны качества. Извлечение
claim и основание expected проверяет человек.
"""

import math

# Заранее описанная точность сравнения (абсолютная погрешность).
TOLERANCE = 1e-9


def _is_finite_number(value):
    """Конечное число без учёта bool (bool — не числовое утверждение)."""
    if isinstance(value, bool):
        return False
    if not isinstance(value, (int, float)):
        return False
    return math.isfinite(value)


def evaluate(case):
    """Верни {'mark': 'прошёл'/'не прошёл'/'спорно', 'reason': объяснение}."""
    if not isinstance(case, dict):
        raise TypeError("case должен быть словарём с полями expected и claim")

    expected = case.get("expected")
    claim = case.get("claim")

    # Основание expected тоже обязано быть конечным числом: иначе правилу
    # нечего сравнивать — это спорный случай проверки, а не ошибка модели.
    if not _is_finite_number(expected):
        return {
            "mark": "спорно",
            "reason": (
                "expected не является однозначным конечным числом "
                f"(получено {expected!r}); сравнение невозможно, проверь "
                "независимый SQL-результат"
            ),
        }

    # Числовое утверждение отсутствует или не извлекается однозначно.
    if not _is_finite_number(claim):
        return {
            "mark": "спорно",
            "reason": (
                "в ответе нет однозначного конечного числового утверждения "
                f"(claim = {claim!r}; bool/строка/NaN/бесконечность/null "
                "числом не считаются)"
            ),
        }

    if abs(claim - expected) <= TOLERANCE:
        return {
            "mark": "прошёл",
            "reason": (
                f"конечное число в ответе ({claim}) совпадает с независимым "
                f"SQL-ожиданием ({expected}) в пределах погрешности {TOLERANCE:g}"
            ),
        }

    return {
        "mark": "не прошёл",
        "reason": (
            f"конечное число в ответе ({claim}) не совпадает с независимым "
            f"SQL-ожиданием ({expected}); расхождение "
            f"{abs(claim - expected):g} превышает погрешность {TOLERANCE:g}"
        ),
    }
